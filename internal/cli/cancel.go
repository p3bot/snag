package cli

import (
	"context"
	"errors"
)

// abortErr returns ctx.Err() or err when the run was cancelled, else nil.
func abortErr(ctx context.Context, err error) error {
	if ctx != nil && ctx.Err() != nil {
		return ctx.Err()
	}
	if errors.Is(err, context.Canceled) {
		return err
	}
	return nil
}
